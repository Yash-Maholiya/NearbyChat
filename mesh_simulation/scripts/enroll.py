"""
Trusted enrolment (simulated QR code step).

Generates a key file per node in mesh_simulation/keys/ (private, git ignored) and writes the public
half of every identity to config/trusted_peers.json, printing the short authentication string (SAS)
that two people would compare before trusting a device.

  python -m mesh_simulation.scripts.enroll nodeA nodeB nodeC nodeD
"""

import argparse
import os

from mesh_simulation.node_app.crypto import NodeCrypto
from mesh_simulation.node_app.trust import TrustedRegistry

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = os.path.join(BASE, "keys")
TRUSTED = os.path.join(BASE, "config", "trusted_peers.json")


def enroll(names, keys_dir=KEYS, trusted_path=TRUSTED):
    registry = TrustedRegistry()
    if os.path.exists(trusted_path):
        try:
            registry = TrustedRegistry.load(trusted_path)
        except (ValueError, KeyError):
            registry = TrustedRegistry()
    rows = []
    for name in names:
        crypto = NodeCrypto.load_or_create(os.path.join(keys_dir, f"{name}.json"))
        node_id = registry.enroll(name, crypto.verify_key_b64, crypto.public_key_b64)
        rows.append((name, node_id, crypto.sas))
    registry.save(trusted_path, "Public keys of enrolled nodes. Generated by scripts/enroll.py. "
                                "Private keys stay in mesh_simulation/keys/ and are never committed.")
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description="Enrol mesh nodes into the trusted registry")
    ap.add_argument("names", nargs="+")
    ap.add_argument("--keys-dir", default=KEYS)
    ap.add_argument("--trusted", default=TRUSTED)
    args = ap.parse_args(argv)
    for name, node_id, sas in enroll(args.names, args.keys_dir, args.trusted):
        print(f"{name:10s} id={node_id}  SAS={sas}")
    print(f"Registry written to {args.trusted}")


if __name__ == "__main__":
    main()
